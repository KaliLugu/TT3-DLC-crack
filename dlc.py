def die(msg):
    print('ERROR: ' + msg, file=sys.stderr)
    sys.exit(1)


def ci(parent, name):
    """Nom réel sur le disque quelle que soit la casse (le jeu écrit 'Common' ou 'COMMON')."""
    try:
        for e in os.listdir(parent):
            if e.lower() == name.lower():
                return os.path.join(parent, e)
    except OSError:
        pass
    return os.path.join(parent, name)


def ci_path(base, *parts):
    for p in parts:
        base = ci(base, p)
    return base


def is_game(d):
    return os.path.isfile(ci(d, 'TT3.exe')) and os.path.isdir(ci_path(d, 'WIN32', 'PKG'))


def steam_libraries():
    home = os.path.expanduser('~')
    roots = []
    if os.name == 'nt':
        for v in ('ProgramFiles(x86)', 'ProgramFiles'):
            if os.environ.get(v):
                roots.append(os.path.join(os.environ[v], 'Steam'))
        try:
            import winreg
            k = winreg.OpenKey(winreg.HKEY_CURRENT_USER, r'Software\Valve\Steam')
            roots.append(winreg.QueryValueEx(k, 'SteamPath')[0])
        except OSError:
            pass
    else:
        roots += [os.path.join(home, '.steam', 'steam'),
                  os.path.join(home, '.local', 'share', 'Steam'),
                  os.path.join(home, '.var', 'app', 'com.valvesoftware.Steam', '.local', 'share', 'Steam'),
                  os.path.join(home, 'Library', 'Application Support', 'Steam')]
    libs = []
    for r in roots:
        if not os.path.isdir(r):
            continue
        libs.append(r)
        # Les bibliothèques des autres disques sont listées ici, antislashs doublés.
        vdf = os.path.join(r, 'steamapps', 'libraryfolders.vdf')
        try:
            with open(vdf, encoding='utf-8', errors='replace') as f:
                for m in re.finditer(r'"path"\s+"([^"]+)"', f.read()):
                    libs.append(m.group(1).replace('\\\\', '\\'))
        except OSError:
            pass
    return libs


def find_game():
    here = os.path.dirname(os.path.abspath(__file__))
    cands = []
    d = here
    while True:
        cands.append(d)
        up = os.path.dirname(d)
        if up == d:
            break
        d = up
    cands.append('/mnt/proton/TT3')
    for lib in steam_libraries():
        common = os.path.join(lib, 'steamapps', 'common')
        try:
            cands += [os.path.join(common, e) for e in sorted(os.listdir(common))]
        except OSError:
            pass
    for c in cands:
        if is_game(c):
            return c
    die('game folder not found: pass it with --game "FOLDER" (the one containing TT3.exe)')


def locate_entry(pkgdir):
    """(fichier PKG, position de la 1re lettre du nom, cette lettre) de l'entrée DLC.LUA.

    Index PPKG, après l'en-tête de 0x30 octets : longueur du nom (4 octets), nom, 80 octets.
    Un '#' en 1re lettre cache l'entrée : le jeu lit alors le fichier en vrac.
    """
    want = ENTRY.encode()
    hidden = b'#' + want[1:]
    found = []
    for e in sorted(os.listdir(pkgdir)):
        if not e.lower().endswith('.pkg'):
            continue
        path = os.path.join(pkgdir, e)
        with open(path, 'rb') as f:
            h = f.read(0x30)
            if len(h) < 0x30 or h[:4] != b'PPKG':
                continue
            count = int.from_bytes(h[8:12], 'little')
            isize = int.from_bytes(h[12:16], 'little')
            idx = f.read(isize)
        p = 0
        for _ in range(count):
            nl = int.from_bytes(idx[p:p + 4], 'little')
            name = idx[p + 4:p + 4 + nl]
            if name in (want, hidden):
                found.append((path, 0x30 + p + 4, name[:1]))
            p += 4 + nl + 80
    if not found:
        die('entry %s not found in %s' % (ENTRY, pkgdir))
    if len(found) > 1:
        die('duplicate entry in the PKGs: %s' % ENTRY)
    return found[0]


def set_byte(path, off, b):
    with open(path, 'r+b') as f:
        f.seek(off)
        f.write(b)


def main():
    args = sys.argv[1:]
    game = cmd = None
    i = 0
    while i < len(args):
        a = args[i]
        if a == '--game' and i + 1 < len(args):
            game = args[i + 1]
            i += 2
            continue
        # Inversé exprès : on = mod actif = DLC désactivés. 'no' = faute de frappe de 'on'.
        if a in ('on', 'no'):
            cmd = 'disable'
        elif a == 'off':
            cmd = 'enable'
        elif a in ('-h', '--help'):
            print(__doc__)
            return
        else:
            die('unknown argument: %s (on, off or --game FOLDER)' % a)
        i += 1

    if game is None:
        game = find_game()
    elif not is_game(game):
        die('no TT3.exe or WIN32/PKG in %s' % game)
    print('Game: ' + game)
    pkgdir = ci_path(game, 'WIN32', 'PKG', 'CHUNK_0')
    if not os.path.isdir(pkgdir):
        die('PKG folder not found: ' + pkgdir)
    dst = ci_path(game, 'Common', 'Settings', 'DLC.LUA')
    pkg, off, cur = locate_entry(pkgdir)                     # cur = b'C' (normal) ou b'#' (masqué)

    off_ids = set()
    if os.path.isfile(dst):
        with open(dst, 'rb') as f:
            data = f.read()
        if not data.startswith((MARK,) + OLD_MARKS):
            die(dst + ' already exists and was not written by this script: leaving it alone')
        if cur != b'#':
            print('WARNING: loose file present but PKG entry not masked (the game ignores it)')
        off_ids = {n for n, _, appid in DLCS if ('appid = %d,' % appid).encode() not in data}
    elif cur == b'#':
        if cmd != 'enable':
            die('PKG entry masked but no loose file: the game will crash. Run: dlc.py off')

    try:
        if cmd == 'disable':
            real = {appid for _, _, appid in DLCS}
            if not isinstance(FAKE_APPID, int) or not 1 <= FAKE_APPID <= 0xFFFFFFFF \
                    or FAKE_APPID in real:
                die('FAKE_APPID: invalid value %r (integer 1..4294967295, not a real DLC appid)'
                    % (FAKE_APPID,))
            data = MARK + ORIGINAL
            for n, _, appid in DLCS:
                old = ('appid = %d,' % appid).encode()
                if old not in data:
                    die('appid of DLC %d not found in the embedded DLC.LUA' % n)
                # Ligne clé : le jeu demandera BIsDlcInstalled(FAKE_APPID) à Steam.
                data = data.replace(old, ('appid = %d,' % FAKE_APPID).encode())
            # Fichier d'abord, masque ensuite : interrompu entre les deux, le jeu lit encore le PKG.
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, 'wb') as f:
                f.write(data)
            if cur != b'#':
                set_byte(pkg, off, b'#')
            off_ids = {n for n, _, _ in DLCS}
        elif cmd == 'enable':
            # Démasquer avant de supprimer, pour que le jeu ait toujours un DLC.LUA à lire.
            if cur != b'C':
                set_byte(pkg, off, b'C')
            if os.path.isfile(dst):
                os.remove(dst)
            off_ids = set()
    except PermissionError as e:
        die('access denied (%s): close the game, or run as administrator' % e.filename)

    for n, name, _ in DLCS:
        print('  %d  %-44s %s' % (n, name, 'disabled' if n in off_ids else 'enabled'))
    if cmd:
        print('Restart the game to apply.')


if __name__ == '__main__':
    main()
