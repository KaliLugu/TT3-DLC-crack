r'''Enable or disable all DLC of TT Isle of Man 3 (Steam version).
Python 3.6+ only, no external module: Windows, Linux, macOS.
  python3 dlc.py            show DLC status
  python3 dlc.py on         disable all DLC (mod on)
  python3 dlc.py off        enable all DLC (mod off = original game)
  python3 dlc.py on --game "D:\SteamLibrary\steamapps\common\TT3"
Without --game, the game folder is searched for: the script folder and its parents,
/mnt/proton/TT3, then the Steam libraries (folder containing TT3.exe).

How it works: the game reads COMMON\SETTINGS\DLC.LUA (inside a PKG), which gives the
Steam appid of each DLC, then asks Steam whether each appid is installed. To disable,
a loose Common/Settings/DLC.LUA is written with a fake appid (FAKE_APPID), and the
PKG entry is masked (1 byte: 'C' -> '#'). To enable, the entry is unmasked and the
loose file removed.'''

